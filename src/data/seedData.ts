function daysAgoIso(daysAgo: number, hourUtc = 14): string {
  const d = new Date();
  d.setUTCDate(d.getUTCDate() - daysAgo);
  d.setUTCHours(hourUtc, 15, 0, 0);
  return d.toISOString();
}

